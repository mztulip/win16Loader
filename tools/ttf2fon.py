#!/usr/bin/env python3
"""ttf2fon.py - wyrenderuj font TrueType do bitmapowego .FON (FNT 3.0 w kontenerze NE).

Uzycie:
  tools/ttf2fon.py WZOR.fon CZCIONKA.ttf WYJSCIE.fon --face "MS Sans Serif" --weight 700 \
      --module "MS SansSerifB" --size PX:WYS:ASC:INTLEAD:PT [--size ...]

WZOR.fon daje naglowek NE i tablice zasobow; liczba --size musi rownac sie liczbie jego fontow.
Znaki 0x20..0xFF wg CP1252, renderowane w skali 8x i progowane (--threshold): hinting
FreeType w trybie jednobitowym gubil w malych rozmiarach np. poprzeczke litery t.
Wymaga Pillow; potrzebne tylko do wygenerowania pliku, nie do budowania projektu.
"""
import argparse, struct
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0xFF


SCALE = 8


def fnt(font, face, weight, h, asc, intlead, pt, threshold):
    glyphs = []
    for c in range(FIRST, LAST + 1):
        try:
            ch = bytes([c]).decode('cp1252')
        except UnicodeDecodeError:
            ch = '\xa0'
        if c == 0xA0:
            ch = ' '
        w = max(1, round(font.getlength(ch) / SCALE))
        big = Image.new('L', (w * SCALE, h * SCALE), 0)
        ImageDraw.Draw(big).text((0, asc * SCALE), ch, font=font, fill=255, anchor='ls')
        small = big.resize((w, h), Image.BOX)
        img = small.point(lambda v: 1 if v >= threshold else 0, '1')
        cols = bytearray()
        for col in range((w + 7) // 8):          # kolumny bajtow, kazda h wierszy
            for y in range(h):
                b = 0
                for bit in range(8):
                    x = col * 8 + bit
                    if x < w and img.getpixel((x, y)):
                        b |= 0x80 >> bit
                cols.append(b)
        glyphs.append((w, bytes(cols)))
    hdr = 148
    n = LAST - FIRST + 2                         # ostatni wpis: znak zastepczy
    bits = hdr + n * 6
    tab, data = b'', b''
    for w, g in glyphs:
        tab += struct.pack('<HI', w, bits + len(data))
        data += g
    tab += struct.pack('<HI', glyphs[0][0], bits)
    faceoff = bits + len(data)
    body = tab + data + face.encode('ascii') + b'\0'
    size = hdr + len(body)
    widths = [w for w, _ in glyphs]
    avg = round(font.getlength('x') / SCALE)
    head = struct.pack('<HI60s', 0x300, size, b'Generated by tools/ttf2fon.py; see fonts/README.md')
    head += struct.pack('<HHHHHHHBBBHBHHBHHBBBBHIIIIB',
                        0, pt, 96, 96, asc, intlead, 0, 0, 0, 0, weight, 0, 0, h, 0x21, avg,
                        max(widths), FIRST, LAST, ord('?') - FIRST, 0, (max(widths) + 7) // 8, 0, faceoff, 0,
                        bits, 0)
    head += struct.pack('<I', 0x10) + struct.pack('<HHH', 0, 0, 0) + struct.pack('<I', 0) + bytes(16)
    assert len(head) == hdr, len(head)
    return head + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('template'); ap.add_argument('ttf'); ap.add_argument('out')
    ap.add_argument('--face', required=True); ap.add_argument('--weight', type=int, default=700)
    ap.add_argument('--module', required=True)
    ap.add_argument('--size', action='append', required=True)
    ap.add_argument('--threshold', type=int, default=90)
    a = ap.parse_args()
    d = bytearray(open(a.template, 'rb').read())
    ne = struct.unpack_from('<I', d, 0x3C)[0]
    rn = ne + struct.unpack_from('<H', d, ne + 0x26)[0]
    if len(a.module) != d[rn]:
        raise SystemExit(f'nazwa modulu musi miec {d[rn]} znakow')
    d[rn + 1:rn + 1 + d[rn]] = a.module.encode('ascii')
    rt = ne + struct.unpack_from('<H', d, ne + 0x24)[0]
    sh = struct.unpack_from('<H', d, rt)[0]
    p, ents = rt + 2, []
    while True:
        ty, n = struct.unpack_from('<HH', d, p)
        if not ty:
            break
        p += 8
        for _ in range(n):
            if ty == 0x8008:
                ents.append(p)
            p += 12
    if len(ents) != len(a.size):
        raise SystemExit(f'wzor ma {len(ents)} fontow')
    out = bytes(d[:struct.unpack_from('<H', d, ents[0])[0] << sh])
    for ent, s in zip(ents, a.size):
        px, h, asc, il, pt = (int(x) for x in s.split(':'))
        font = ImageFont.truetype(a.ttf, px * SCALE, layout_engine=ImageFont.Layout.BASIC)
        data = fnt(font, a.face, a.weight, h, asc, il, pt, a.threshold)
        out += bytes(-len(out) & ((1 << sh) - 1))
        d2 = bytearray(out)
        struct.pack_into('<HH', d2, ent, len(out) >> sh, (len(data) + (1 << sh) - 1) >> sh)
        out = bytes(d2) + data
    open(a.out, 'wb').write(out)


if __name__ == '__main__':
    main()
